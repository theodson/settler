#!/usr/bin/env bash
#
# inject-firstboot.sh
#
# Splice the settler-firstboot service installer into the packer provisioning
# scripts, so a box comes out of `bin/build` with the service already inside it.
#
# Why this exists rather than a copy-paste
# ----------------------------------------
# The first-boot service needs to exist in two places:
#
#   bin/vm-generalize.sh   run inside a booted guest, by `bin/package`
#   scripts/{arm,amd64}.sh run inside the guest by packer, during the build
#
# Keeping two hand-maintained copies of a ~90 line systemd unit and shell script
# guarantees they drift. Instead bin/vm-generalize.sh owns the definition,
# between the SETTLER_FIRSTBOOT_BEGIN/END markers, and this script lifts it out
# verbatim and splices it into the build scripts. Same bytes in both places, by
# construction.
#
# This follows the existing settler convention: bin/use-homestead-features.sh
# already injects feature scripts into scripts/*.sh with `sed -e "Nr file"`, and
# bin/build resets those files with `git checkout` before each run.
#
# Where it lands
# --------------
# Immediately before the existing
#
#     # Blank netplan machine-id (DUID) so machines get unique ID generated on boot.
#     truncate -s 0 /etc/machine-id
#
# in the tidy section at the end of each script - the same point the build
# already generalizes the image, and the last thing to run before packer shuts
# the VM down.
#
# What is deliberately NOT injected
# ---------------------------------
# Removing the guest's SSH host keys. That would make the built box fully
# generalized, but the removal would happen in packer's final provisioner,
# and packer still has to run its shutdown_command over ssh afterwards. An
# established session survives the key files being deleted; a reconnect would
# not. That is a 40-minute build failing at the last step, and it is not
# something this repo has ever exercised.
#
# So: the service is baked in, and `bin/package` (which boots the VM and runs
# bin/vm-generalize.sh properly) remains what strips the host keys. Set
# SETTLER_STRIP_SSH_KEYS=1 to inject the removal as well, once you have had a
# successful build to confirm it is safe on your packer version.
#
# Usage
# -----
#   bin/inject-firstboot.sh            # inject into scripts/arm.sh + amd64.sh
#   bin/inject-firstboot.sh --check    # exit 1 if not injected or drifted
#   bin/inject-firstboot.sh --remove   # strip the injected block back out
#
# Idempotent: re-running replaces a previously injected block rather than
# stacking a second copy.
#
set -euo pipefail

settler_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_script="$settler_root/bin/vm-generalize.sh"

BEGIN_MARK='# >>> SETTLER_FIRSTBOOT_BEGIN'
END_MARK='# <<< SETTLER_FIRSTBOOT_END'
INJ_BEGIN='# >>> settler-firstboot (generated by bin/inject-firstboot.sh - do not edit)'
INJ_END='# <<< settler-firstboot'
ANCHOR='truncate -s 0 /etc/machine-id'

MODE="inject"
case "${1:-}" in
--check)  MODE="check" ;;
--remove) MODE="remove" ;;
-h | --help)
    sed -n '3,62p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
"") ;;
*) echo "✋ unknown option: $1" >&2; exit 1 ;;
esac

[ -e "$source_script" ] || { echo "✋ cannot find $source_script"; exit 1; }

#
# lift the canonical block out of bin/vm-generalize.sh
#
payload="$(mktemp)"
trap 'rm -f "$payload" "$payload.body"' EXIT

awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
    index($0, b) { inblock = 1; next }
    index($0, e) { inblock = 0; next }
    inblock      { print }
' "$source_script" >"$payload.body"

if [ ! -s "$payload.body" ]; then
    echo "✋ no content between the SETTLER_FIRSTBOOT markers in $source_script"
    echo "   Has bin/vm-generalize.sh been edited?"
    exit 1
fi

{
    echo "$INJ_BEGIN"
    echo "# Source: bin/vm-generalize.sh - edit it there, then re-run bin/inject-firstboot.sh"
    echo "echo '==> installing settler-firstboot.service'"
    # Verbatim, indentation and all. It is tempting to dedent - the block is
    # indented for its `if` in vm-generalize.sh and sits at top level here - but
    # a blanket `sed 's/^    //'` also eats the indentation *inside* the two
    # heredocs, so the settler-firstboot script written into the guest would no
    # longer be byte-identical to the one vm-generalize.sh writes. Leading
    # whitespace before a top-level command is meaningless to bash, and the
    # heredoc terminators are already at column 0, so copying it unchanged is
    # both simpler and the only way --check can mean what it says.
    cat "$payload.body"
    if [ "${SETTLER_STRIP_SSH_KEYS:-0}" = "1" ]; then
        echo ""
        echo "# SETTLER_STRIP_SSH_KEYS=1 was set when this was injected."
        echo "# sshd is deliberately not restarted - packer's shutdown_command"
        echo "# still needs the ssh session it already has."
        echo "rm -f /etc/ssh/ssh_host_*"
    fi
    # Trailing blank line goes INSIDE the markers. If it sat after INJ_END the
    # strip pass would not remove it, so a freshly injected file would not
    # round-trip and --check would report drift that is not there.
    echo ""
    echo "$INJ_END"
} >"$payload"

#
# apply to each build script
#
status=0
for target in "$settler_root/scripts/arm.sh" "$settler_root/scripts/amd64.sh"; do
    name="$(basename "$target")"

    if [ ! -e "$target" ]; then
        echo "⚠️  $name not found, skipping"
        continue
    fi

    # always start from a copy with any previous injection removed
    stripped="$(mktemp)"
    awk -v b="$INJ_BEGIN" -v e="$INJ_END" '
        index($0, b) { inblock = 1; next }
        index($0, e) { inblock = 0; next }
        !inblock     { print }
    ' "$target" >"$stripped"

    case "$MODE" in
    remove)
        if cmp -s "$stripped" "$target"; then
            echo "   $name - nothing injected"
        else
            cat "$stripped" >"$target"
            echo "🧹 $name - injected block removed"
        fi
        rm -f "$stripped"
        continue
        ;;
    esac

    if ! grep -qF "$ANCHOR" "$stripped"; then
        echo "✋ $name has no '$ANCHOR' line to anchor to."
        echo "   The tidy section of the build script must have changed."
        rm -f "$stripped"
        exit 1
    fi

    # Rebuild with the payload spliced in above the anchor - and above the
    # comment block that introduces it, so the anchor keeps the comment that
    # explains it rather than having 90 lines wedged between the two.
    rebuilt="$(mktemp)"
    awk -v anchor="$ANCHOR" -v payload="$payload" '
        { lines[NR] = $0 }
        END {
            for (i = 1; i <= NR; i++)
                if (index(lines[i], anchor)) { a = i; break }

            ins = a
            while (ins > 1 && lines[ins - 1] ~ /^[[:space:]]*#/) ins--

            for (i = 1; i < ins; i++) print lines[i]
            while ((getline line < payload) > 0) print line
            close(payload)
            for (i = ins; i <= NR; i++) print lines[i]
        }
    ' "$stripped" >"$rebuilt"

    case "$MODE" in
    check)
        if cmp -s "$rebuilt" "$target"; then
            echo "✅ $name - up to date"
        else
            if cmp -s "$stripped" "$target"; then
                echo "✋ $name - firstboot service NOT injected"
            else
                echo "✋ $name - injected block has DRIFTED from bin/vm-generalize.sh"
            fi
            status=1
        fi
        ;;
    inject)
        cat "$rebuilt" >"$target"
        echo "📦 $name - settler-firstboot injected ($(wc -l <"$payload" | tr -d ' ') lines)"
        ;;
    esac

    rm -f "$stripped" "$rebuilt"
done

if [ "$MODE" = "check" ] && [ "$status" != 0 ]; then
    echo
    echo "   Run: bin/inject-firstboot.sh"
fi

exit "$status"
